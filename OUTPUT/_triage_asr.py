# -*- coding: utf-8 -*-
"""ASR 缺陷分级 —— 把 _asr_audit.txt 的 25 处置疑按「是否必须重跑」分类。

分级口径（★ 重跑很贵：单镜 5–15 分钟 + 要重新抽帧/ASR 验收）
    P0 必须重跑：**语义错误**。改掉了意思 / 说了不该说的话 / 名字错了 / 卡片乱说话
       · 稻子→豆子/哨子/瘦子（4 处，道具核心名词，观众会听出来）
       · 继光→季光/激光（2 处，黄继光的姓名，史实人物）
       · 舞台指示被念出来（镜 97「他平静地说：」）
       · 卡片镜乱说话（镜 46/74/105，本该无台词）
       · 台词重复 3 遍（镜 18）
       · 丢掉整句（镜 3「飞喽」→「飞了」）
       · 多出整句（镜 32「不用再打仗了」，且与 storyboard 已删冲突）
    P1 建议重跑：**错字/丢字但不改意思**，观众可能听不出来但字幕会对不上
       · 物资→日再（镜 22）、多→都（镜 108）、戴→带（镜 103）
       · 丢字（镜 30 丢「AI」、镜 31 丢「你」、镜 31/72 语助词）
    P2 可接受：**前导乱音/语气词**，台词本体完全正确，靠后期静音可解
       · 镜 7/25/69/71/89/101/108（前导 1 词乱音）

用法：
    py -3.10 OUTPUT/_triage_asr.py
"""
from __future__ import annotations
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# ★ 人工判定表：镜 → (级别, 类别, 说明)
TRIAGE = {
    # ── P0 语义错误，必须重跑 ────────────────────────────────────
    3:   ("P0", "丢整句", "「飞喽——！」念成「飞了！」（拟声+拖长腔丢失）"),
    18:  ("P0", "台词重复", "「那就——进模型。」念了 3 遍"),
    32:  ("P0", "多出整句", "多念「不用再打仗了」；该句 storyboard 已定删（6s→4s），脚本未同步 ⇒ 双重缺陷"),
    36:  ("P0", "人名错", "「继光哥」→「季光哥」（黄继光姓名）"),
    42:  ("P0", "人名错", "「继光！」→「激光营部通知」（黄继光姓名 + 断句错）"),
    46:  ("P0", "卡片乱说话", "白屏日记卡本应无台词，实得「大妹子。」"),
    55:  ("P0", "名词错", "「稻子」→「豆子」"),
    57:  ("P0", "名词错", "「稻子」→「哨子」"),
    60:  ("P0", "名词错", "「稻子多结」→「瘦子多节」"),
    61:  ("P0", "人名错", "「袁爷爷」→「原夜，原夜」"),
    70:  ("P0", "名词错", "「稻子」→「豆子」"),
    74:  ("P0", "卡片乱说话", "白屏日记卡本应无台词，实得「谁了？」"),
    97:  ("P0", "舞台指示被念", "「他平静地说：」被当台词念出来（+ 纪录→记录）"),
    105: ("P0", "卡片乱说话", "白屏日记卡本应无台词，实得「嗯。」"),
    # ── P1 错字/丢字，建议重跑 ──────────────────────────────────
    22:  ("P1", "错字", "「物资」→「日再」"),
    30:  ("P1", "丢字", "丢了「AI——」（三个列举只念了两个）"),
    31:  ("P1", "丢字", "丢了「你」（你慢点 → 慢点儿）"),
    72:  ("P1", "错字", "「种不种得活」→「种不种的活」"),
    103: ("P1", "错字", "「戴好」→「带好」（口罩语境，错字刺眼）"),
    108: ("P1", "错字+乱音", "「所有人」→「所有人都」；且有前导「心很稳，」"),
    # ── P2 前导乱音（台词本体正确，后期静音可解）──────────────
    7:   ("P2", "前导乱音", "「上医院去旋转手术室。」"),
    25:  ("P2", "前导乱音", "「说到一电挑，」"),
    69:  ("P2", "前导乱音", "「想了，」"),
    71:  ("P2", "前导乱音", "「尽下了，」"),
    89:  ("P2", "追加乱音", "「不凶。」"),
    101: ("P2", "前导乱音", "「好，」"),
}


def main():
    dest = os.path.join(HERE, "_asr_triage.txt")
    by = {}
    for n, (lvl, kind, why) in sorted(TRIAGE.items()):
        by.setdefault(lvl, []).append((n, kind, why))
    lines = []
    lines.append("ASR 缺陷分级（共 %d 镜）" % len(TRIAGE))
    lines.append("=" * 96)
    for lvl in ("P0", "P1", "P2"):
        rows = by.get(lvl, [])
        lines.append("")
        lines.append("【%s】%d 镜" % (lvl, len(rows)))
        lines.append("-" * 96)
        for n, kind, why in rows:
            lines.append("  镜 %-4d %-12s %s" % (n, kind, why))
    txt = "\n".join(lines)
    print(txt)
    io.open(dest, "w", encoding="utf-8").write(txt + "\n")
    print("\n-> %s" % dest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
