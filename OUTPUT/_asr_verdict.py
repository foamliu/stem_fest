# -*- coding: utf-8 -*-
"""ASR 终态裁定表 —— 把 `_audit_asr.py` 判为 miss/extra 的镜**逐条人工定性**。

★ 为什么需要人工表
    `_audit_asr.py` 的判定是**字符串包含**，它会把下列情况一律报 miss/extra：
      · **刻意改写**（为规避同音错而换词，见 SUBST）
      · **一镜内换人说话**（台词串里第二人的句子对不上第一条）
      · **同音字变体**（纪录/记录、戴/带、粒实/粒石）—— 读音相同，语义不变
      · **前后 1 词乱音** —— 台词本体正确，只是 H3 多吐了半句
    这些**不是缺陷**。本表把每条的**实际影响**与**处置**写清楚，作为最终裁定。

用法：
    py -3.10 OUTPUT/_asr_verdict.py
"""
from __future__ import annotations
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# 镜 → (级别, 定性, 处置)
VERDICT = {
    7:   ("P2", "前导乱音「上医院去旋转手术室。」", "台词本体正确。后期静音首 0.9s（已试 `_v2norm`），或接受"),
    39:  ("OK", "提取器把「接着另一个更沉稳的声音应了一声」也算作期望台词；ASR 实得为空/正确",
          "无语义问题。换人句由「说好了」承接，正确"),
    46:  ("OK", "白屏日记卡**本应零台词**；ASR 返回空串 ⇒ **正确**",
          "已修（Audio 去掉「听不清任何词句」）。无需处置"),
    60:  ("OK", "同音字变体：饿倒→恶岛（字幕**由烧字卡/字幕轨提供**，不依赖 ASR）；粒实→粒石",
          "语义不变。禾苗已正确。可接受"),
    74:  ("OK", "白屏日记卡**本应零台词**；ASR 返回空串 ⇒ **正确**", "已修。无需处置"),
    80:  ("OK", "双人对话：提取器拼了两人台词；ASR 实得「钟南山。钟南山爷爷。」⇒ **正确**", "无须处置"),
    85:  ("OK", "双人对话：提取器拼了两人台词；ASR 实得「吃了，那就好。」⇒ **正确**", "无须处置"),
    89:  ("P2", "尾部乱音「不凶。」（2 seed 均复现）", "台词本体正确。后期裁掉尾 0.6s，或接受"),
    97:  ("OK", "同音字变体：纪录→记录（jì lù，读音相同）", "语义不变。舞台指示已消除（本轮主要修复）"),
    103: ("OK", "同音字变体：戴→带（dài）", "语义不变（口罩语境由画面提供）。可接受"),
    105: ("P2", "白屏转场镜仍吐 1 词（3 seed：嗯/抑郁三/嗯）", "★ 该镜**末 3 秒是纯白**，后期裁掉末 1s 即可，或接受"),
}


def main():
    out = ["ASR 终态裁定（%d 条）" % len(VERDICT), "=" * 92]
    for n, (lvl, why, act) in sorted(VERDICT.items()):
        out.append("  镜 %-4d [%s] %s\n            处置：%s" % (n, lvl, why, act))
    txt = "\n".join(out)
    print(txt)
    io.open(os.path.join(HERE, "_asr_verdict.txt"), "w", encoding="utf-8").write(txt + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
